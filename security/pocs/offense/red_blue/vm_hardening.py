def main():
    parser = argparse.ArgumentParser(description="VM Hardening Deployment")
    parser.add_argument("--verify", action="store_true", help="Only verify, don't deploy")
    parser.add_argument("--rollback", action="store_true", help="Undo all hardening")
    args = parser.parse_args()

    print()
    print("=" * 60)
    print("  VM HARDENING — Exercise-Driven OS Security")
    print("=" * 60)
    print()

    ssh = ssh_connect()
    print("  SSH connected.\n")

    if args.rollback:
        rollback_all(ssh)
    elif args.verify:
        verify_all(ssh)
    else:
        phase1_packages(ssh)
        phase2_auditd(ssh)
        phase3_apparmor(ssh)
        phase4_logs(ssh)
        phase5_ids(ssh)
        phase6_suid(ssh)
        phase7_systemd(ssh)
        phase8_ssh(ssh)
        phase9_fail2ban(ssh)
        phase10_crontab(ssh)
        verify_all(ssh)

    ssh.close()
    print("\n  Done.")
    print("=" * 60)


if __name__ == "__main__":
    main()
