def phase10_crontab(ssh):
    print("  [10/10] Making crontab immutable...", end="", flush=True)
    # Remove any existing crontab
    sudo(ssh, "crontab -r -u vibemind 2>/dev/null")
    # Ensure file exists
    sudo(ssh, "touch /var/spool/cron/crontabs/vibemind")
    sudo(ssh, "chown vibemind:crontab /var/spool/cron/crontabs/vibemind")
    sudo(ssh, "chmod 600 /var/spool/cron/crontabs/vibemind")
    # Remove immutable first (in case already set), then set it
    sudo(ssh, "chattr -i /var/spool/cron/crontabs/vibemind 2>/dev/null")
    sudo(ssh, "chattr +i /var/spool/cron/crontabs/vibemind")

    # Verify
    out, _, _ = sudo(ssh, "lsattr /var/spool/cron/crontabs/vibemind 2>/dev/null")
    immutable = "i" in (out.split()[0] if out.strip() else "")
    print(f" OK ({'IMMUTABLE' if immutable else 'FAILED'})")


