SSH_HARDENING = """# VM Hardening — deployed by vm_hardening.py
PermitRootLogin no
MaxAuthTries 3
LoginGraceTime 30
ClientAliveInterval 300
ClientAliveCountMax 2
X11Forwarding no
AllowTcpForwarding no
PermitTunnel no
# Keep password auth for exercise
PasswordAuthentication yes
"""


def phase8_ssh(ssh):
    print("  [8/10] Hardening SSH...", end="", flush=True)
    deploy_file(ssh, SSH_HARDENING, "/etc/ssh/sshd_config.d/hardening.conf")

    # CRITICAL: validate config before restart
    out, err, rc = sudo(ssh, "sshd -t")
    if rc != 0:
        print(f" FAILED (sshd -t error: {err[:80]})")
        sudo(ssh, "rm /etc/ssh/sshd_config.d/hardening.conf")
        return

    sudo(ssh, "systemctl restart sshd")
    time.sleep(2)

    # Verify SSH still works by running a command
    out2, _, rc2 = run(ssh, "echo SSH_OK")
    if "SSH_OK" in out2:
        print(" OK (SSH verified)")
    else:
        print(" WARNING (SSH may be impacted)")


