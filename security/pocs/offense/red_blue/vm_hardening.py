SUID_KEEP = {
    "/usr/bin/su",
    "/usr/bin/sudo",
    "/usr/bin/passwd",
    "/usr/bin/newgrp",
    "/usr/bin/gpasswd",
    "/usr/bin/chsh",
    "/usr/bin/chfn",
    "/usr/lib/openssh/ssh-keysign",
    "/usr/lib/dbus-1.0/dbus-daemon-launch-helper",
    "/usr/bin/pkexec",
    "/usr/libexec/polkit-agent-helper-1",
    "/usr/lib/policykit-1/polkit-agent-helper-1",
}


def phase6_suid(ssh):
    print("  [6/10] Reducing SUID binaries...", end="", flush=True)
    out, _, _ = sudo(ssh, "find / -perm -4000 -type f 2>/dev/null")
    suid_binaries = [l.strip() for l in out.splitlines() if l.strip()]
    before = len(suid_binaries)

    removed = 0
    for binary in suid_binaries:
        if binary not in SUID_KEEP:
            sudo(ssh, f"chmod u-s {binary} 2>/dev/null")
            removed += 1

    # Give ping CAP_NET_RAW instead of SUID
    sudo(ssh, "setcap cap_net_raw+ep /usr/bin/ping 2>/dev/null")

    # Count remaining
    out2, _, _ = sudo(ssh, "find / -perm -4000 -type f 2>/dev/null | wc -l")
    after = out2.strip()
    print(f" OK ({before} -> {after} SUID binaries, {removed} removed)")


