"""
VM Hardening — Exercise-Driven OS Security Deployment
=========================================================
Deploys 10 hardening phases to MultiseatOS VM via SSH.
Based on Red/Blue exercise gaps (22 GitHub issues).

Usage:
  python vm_hardening.py            # Deploy all phases
  python vm_hardening.py --verify   # Only verify, don't change
  python vm_hardening.py --rollback # Undo all hardening

Idempotent: safe to run multiple times.
"""

import argparse
import logging
import os
import sys
import time

import paramiko

logging.getLogger("paramiko").setLevel(logging.CRITICAL)

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from infra import VM_SSH_HOST, VM_SSH_PORT, VM_SSH_USER, VM_SSH_PASS

SUDO = VM_SSH_PASS


def ssh_connect():
    ssh = paramiko.SSHClient()
    ssh.set_missing_host_key_policy(paramiko.AutoAddPolicy())
    ssh.connect(VM_SSH_HOST, port=VM_SSH_PORT, username=VM_SSH_USER,
                password=VM_SSH_PASS, timeout=10, banner_timeout=15)
    return ssh


def run(ssh, cmd, timeout=30):
    _, out, err = ssh.exec_command(cmd, timeout=timeout)
    o = out.read().decode("utf-8", errors="replace").strip()
    e = err.read().decode("utf-8", errors="replace").strip()
    rc = out.channel.recv_exit_status()
    return o, e, rc


def sudo(ssh, cmd, timeout=30):
    return run(ssh, f"echo '{SUDO}' | sudo -S {cmd}", timeout=timeout)


def deploy_file(ssh, content, remote_path):
    sftp = ssh.open_sftp()
    tmp = f"/tmp/hardening_{os.path.basename(remote_path)}"
    with sftp.file(tmp, "w") as f:
        f.write(content)
    sftp.close()
    sudo(ssh, f"cp {tmp} {remote_path}")
    sudo(ssh, f"chmod 644 {remote_path}")
    return remote_path


