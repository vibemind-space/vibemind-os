def verify_all(ssh):
    print("\n  Verification:")
    checks = [
        ("auditd running", "systemctl is-active auditd"),
        ("auditd rules", "sudo auditctl -l 2>/dev/null | wc -l"),
        ("auth.log append-only", "lsattr /var/log/auth.log 2>/dev/null | head -1"),
        ("syslog append-only", "lsattr /var/log/syslog 2>/dev/null | head -1"),
        ("fail2ban running", "systemctl is-active fail2ban"),
        ("SUID count", "find / -perm -4000 -type f 2>/dev/null | wc -l"),
        ("IDS stealth", "systemctl is-active dbus-session-helper"),
        ("IDS decoy", "systemctl is-active vm-security-monitor"),
        ("crontab immutable", "lsattr /var/spool/cron/crontabs/vibemind 2>/dev/null | head -1"),
        ("root login disabled", "grep PermitRootLogin /etc/ssh/sshd_config.d/hardening.conf 2>/dev/null"),
        ("vault healthy", "curl -s http://localhost:8000/api/health"),
        ("monitor healthy", "curl -s http://localhost:9090/api/health"),
    ]

    passed = 0
    for name, cmd in checks:
        out, _, rc = sudo(ssh, cmd) if "sudo" in cmd else run(ssh, cmd)
        ok = rc == 0 and out.strip()
        icon = "OK" if ok else "??"
        print(f"    [{icon}] {name}: {out.strip()[:60]}")
        if ok:
            passed += 1

    print(f"\n  {passed}/{len(checks)} checks passed")
    return passed


