def rollback_all(ssh):
    print("\n  Rolling back hardening...")
    cmds = [
        ("Remove auditd rules", "rm -f /etc/audit/rules.d/hardening.rules && systemctl restart auditd"),
        ("Remove AppArmor profile", "aa-disable /etc/apparmor.d/usr.bin.crontab 2>/dev/null; rm -f /etc/apparmor.d/usr.bin.crontab"),
        ("Remove log protection", "chattr -a /var/log/auth.log /var/log/syslog /var/log/kern.log 2>/dev/null"),
        ("Remove crontab immutable", "chattr -i /var/spool/cron/crontabs/vibemind 2>/dev/null"),
        ("Remove SSH hardening", "rm -f /etc/ssh/sshd_config.d/hardening.conf && systemctl restart sshd"),
        ("Remove fail2ban config", "rm -f /etc/fail2ban/jail.d/ssh-hardening.conf && systemctl restart fail2ban"),
    ]
    for name, cmd in cmds:
        sudo(ssh, cmd)
        print(f"    {name}")
    print("  Rollback complete. SUID binaries not restored (run manually if needed).")


