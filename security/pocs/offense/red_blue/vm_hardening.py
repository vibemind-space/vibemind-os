def phase4_logs(ssh):
    print("  [4/10] Protecting logs (append-only)...", end="", flush=True)
    protected = 0
    for log in ["/var/log/auth.log", "/var/log/syslog", "/var/log/kern.log"]:
        # Check if already protected
        out, _, _ = sudo(ssh, f"lsattr {log} 2>/dev/null")
        if "a" in out.split()[0] if out.strip() else "":
            protected += 1
            continue
        # Ensure file exists
        sudo(ssh, f"touch {log}")
        sudo(ssh, f"chattr +a {log}")
        protected += 1
    print(f" OK ({protected}/3 logs protected)")


