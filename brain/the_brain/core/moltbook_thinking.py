# [11] ThoughtStream — Continuous Background Thinking
# ═══════════════════════════════════════════════════════════════════

class ThoughtStream:
    """
    Continuous background micro-thought generator.

    Runs as a background process, generating internal thoughts every
    100-500ms by combining:
      - Current task context
      - Moltbook knowledge (semantic retrieval)
      - DMN spontaneous associations
      - Emotional modulation

    Thoughts flow into the ThoughtBuffer where they compete for
    conscious broadcast (Global Workspace).
    """

    def __init__(self, moltbook=None, dmn=None, core_affect=None,
                 buffer: Optional[ThoughtBuffer] = None,
                 interval_ms: int = 200):
        self._moltbook = moltbook           # MoltbookStore
        self._dmn = dmn                     # DefaultModeNetwork (optional)
        self._core_affect = core_affect     # CoreAffectSpace (optional)
        self._buffer = buffer or ThoughtBuffer()
        self._interval_ms = interval_ms

        # Thinking components
        self._associative = AssociativeThinking(moltbook=moltbook)
        self._emotional = EmotionalThinking(core_affect=core_affect)

        # State
        self._current_context: str = ""
        self._running = False
        self._thread: Optional[threading.Thread] = None
        self._total_ticks = 0

        # Thought seeds (topics to think about)
        self._seeds: List[str] = []
        self._seed_lock = threading.Lock()

        logger.info(f"ThoughtStream initialized (interval={interval_ms}ms)")

    @property
    def buffer(self) -> ThoughtBuffer:
        """Access the thought buffer."""
        return self._buffer

    @property
    def is_running(self) -> bool:
        return self._running

    def set_context(self, context: str) -> None:
        """Set the current task context for thought generation."""
        self._current_context = context

    def add_seed(self, seed: str) -> None:
        """Add a thought seed — a topic to think about."""
        with self._seed_lock:
            self._seeds.append(seed)
            # Keep last 20 seeds
            if len(self._seeds) > 20:
                self._seeds = self._seeds[-20:]

    def background_tick(self) -> Optional[MicroThought]:
        """
        Generate one micro-thought. Called by AgentLoop during idle,
        or by the background thread.

        Returns the generated thought, or None if nothing to think about.
        """
        self._total_ticks += 1

        # Pick a seed to think about
        seed = self._pick_seed()
        if not seed:
            return None

        # Generate thought via association
        thoughts = self._associative.associate(seed, temperature=0.5, max_results=1)

        if thoughts:
            thought = thoughts[0]
        else:
            # Fallback: simple context-echo thought
            thought = MicroThought(
                content=f"Thinking about: {seed[:100]}",
                relevance_to_current_task=0.3,
                thought_type="reflection",
            )

        # DMN spontaneous association (if available)
        if self._dmn:
            try:
                dmn_result = self._dmn.process({
                    'mode': 'mind_wandering',
                    'seed': seed[:50]
                })
                if isinstance(dmn_result, dict):
                    wandering = dmn_result.get('mind_wandering', {})
                    if isinstance(wandering, dict):
                        novel = wandering.get('novel_combination', '')
                        if novel:
                            thought.content += f" → {str(novel)[:100]}"
            except Exception:
                pass

        # Emotional modulation
        thought = self._emotional.modulate_thought(thought)

        # Add to buffer
        self._buffer.add(thought)
        return thought

    def _pick_seed(self) -> Optional[str]:
        """Pick a seed for thought generation."""
        with self._seed_lock:
            seeds = list(self._seeds)

        candidates = []

        # Current context is always a candidate
        if self._current_context:
            candidates.append(self._current_context)

        # Recent seeds
        candidates.extend(seeds[-5:])

        if not candidates:
            return None

        # Weighted random: current context gets higher weight
        if len(candidates) == 1:
            return candidates[0]

        weights = [2.0] + [1.0] * (len(candidates) - 1)  # Context gets 2x weight
        total = sum(weights)
        r = random.random() * total
        cumulative = 0.0
        for i, w in enumerate(weights):
            cumulative += w
            if r <= cumulative:
                return candidates[i]
        return candidates[0]

    def start(self) -> None:
        """Start background thought generation thread."""
        if self._running:
            return
        self._running = True
        self._thread = threading.Thread(
            target=self._run_loop, daemon=True, name="ThoughtStream"
        )
        self._thread.start()
        logger.info("ThoughtStream started")

    def stop(self) -> None:
        """Stop background thought generation."""
        self._running = False
        if self._thread:
            self._thread.join(timeout=2.0)
            self._thread = None
        logger.info("ThoughtStream stopped")

    def _run_loop(self) -> None:
        """Background loop generating thoughts at configured interval."""
        while self._running:
            try:
                self.background_tick()
            except Exception as e:
                logger.warning(f"ThoughtStream tick error: {e}")
            time.sleep(self._interval_ms / 1000.0)

    def get_relevant_thoughts(self, context: str, top_k: int = 5) -> List[MicroThought]:
        """Get the most relevant thoughts for a given context."""
        return self._buffer.get_workspace(context)[:top_k]

    def get_stats(self) -> Dict[str, Any]:
        return {
            'running': self._running,
            'total_ticks': self._total_ticks,
            'interval_ms': self._interval_ms,
            'buffer': self._buffer.get_stats(),
            'associative': self._associative.get_stats(),
            'emotional': self._emotional.get_state(),
            'seed_count': len(self._seeds),
        }

    @classmethod
    def from_yaml(cls, yaml_config: Dict[str, Any]) -> 'ThoughtStream':
        """Create from YAML config."""
        mb = yaml_config.get('moltbook', {})
        return cls(interval_ms=mb.get('thought_stream_interval_ms', 200))


