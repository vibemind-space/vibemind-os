@dataclass
class MicroThought:
    """
    Single micro-thought — the atomic unit of the ThoughtStream.

    Each micro-thought is a brief internal reflection, association,
    or observation generated by the background thinking process.
    """
    content: str = ""
    relevance_to_current_task: float = 0.0     # 0-1
    emotional_charge: float = 0.0              # -1 (negative) to +1 (positive)
    arousal: float = 0.0                       # 0 (calm) to 1 (excited)
    source_entry_ids: List[str] = field(default_factory=list)
    thought_type: str = "association"          # association/reflection/prediction/memory
    activation: float = 1.0                     # Current activation level (decays)
    created_at: float = field(default_factory=time.time)
    was_conscious: bool = False                 # Was this thought broadcast to GW?

    def decay(self, rate: float = 0.01) -> None:
        """Decay activation over time."""
        age = time.time() - self.created_at
        self.activation = max(0.0, self.activation * math.exp(-rate * age))

    def to_dict(self) -> Dict[str, Any]:
        return {
            'content': self.content,
            'relevance': self.relevance_to_current_task,
            'emotional_charge': self.emotional_charge,
            'arousal': self.arousal,
            'source_entries': self.source_entry_ids,
            'type': self.thought_type,
            'activation': self.activation,
            'created_at': self.created_at,
            'was_conscious': self.was_conscious,
        }


@dataclass
class ThoughtQuality:
    """Assessment of thought stream quality from MetaThinking."""
    productivity: float = 0.5       # How productive are current thoughts (0-1)
    creativity: float = 0.5         # How creative/novel are they (0-1)
    circularity: float = 0.0        # Are thoughts repeating? (0=no, 1=very circular)
    coherence: float = 0.5          # How coherent is the thought chain (0-1)
    value_of_control: float = 0.5   # Is more thinking worth it? (EVC)
    recommendation: str = "continue"  # continue/redirect/pause/deepen

    def to_dict(self) -> Dict[str, Any]:
        return {
            'productivity': self.productivity,
            'creativity': self.creativity,
            'circularity': self.circularity,
            'coherence': self.coherence,
            'evc': self.value_of_control,
            'recommendation': self.recommendation,
        }


