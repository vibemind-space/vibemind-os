# [15] MetaThinking — Thinking About Thinking
# ═══════════════════════════════════════════════════════════════════

class MetaThinking:
    """
    Meta-cognitive monitoring of the thought stream.

    Monitors:
      - Are thoughts productive? (leading toward task resolution)
      - Are thoughts circular? (repeating same patterns)
      - Should we continue thinking? (Expected Value of Control)
      - What's the quality of the thought chain?

    Integration:
      - ACC.expected_value_of_control() for EVC
      - WisdomModule.record_reflection() for wisdom accumulation
    """

    def __init__(self, acc=None, wisdom=None,
                 circularity_threshold: float = 0.7):
        self._acc = acc                    # AnteriorCingulateCortex (optional)
        self._wisdom = wisdom              # WisdomModule (optional)
        self._circularity_threshold = circularity_threshold

        # History for circularity detection
        self._recent_thought_hashes: deque = deque(maxlen=50)
        self._total_evaluations = 0
        self._redirects = 0

        logger.info("MetaThinking initialized")

    def evaluate(self, thoughts: Optional[List[MicroThought]] = None,
                 unified_thought: Optional[Any] = None) -> ThoughtQuality:
        """
        Evaluate the quality of current thoughts.

        Can evaluate either a list of micro-thoughts (from buffer)
        or a unified thought (from InternalMonologue).

        Returns ThoughtQuality assessment with recommendation.
        """
        self._total_evaluations += 1

        if thoughts is None and unified_thought is None:
            return ThoughtQuality(recommendation="continue")

        quality = ThoughtQuality()

        # Evaluate list of micro-thoughts
        if thoughts:
            quality = self._evaluate_thought_list(thoughts, quality)

        # Evaluate unified thought (from thinker)
        if unified_thought:
            quality = self._evaluate_unified(unified_thought, quality)

        # Get EVC from ACC if available
        if self._acc:
            try:
                evc_result = self._acc.process({
                    'task_type': 'thinking',
                    'effort': 0.5,
                    'expected_reward': quality.productivity,
                })
                if isinstance(evc_result, dict):
                    evc = evc_result.get('evc', evc_result.get('expected_value_of_control', 0.5))
                    quality.value_of_control = float(evc) if isinstance(evc, (int, float)) else 0.5
            except Exception:
                pass

        # Record reflection in wisdom module
        if self._wisdom and quality.productivity > 0.7:
            try:
                self._wisdom.record_reflection({
                    'type': 'meta_thinking',
                    'quality': quality.to_dict(),
                })
            except Exception:
                pass

        # Generate recommendation
        quality.recommendation = self._generate_recommendation(quality)

        return quality

    def _evaluate_thought_list(self, thoughts: List[MicroThought],
                                quality: ThoughtQuality) -> ThoughtQuality:
        """Evaluate a list of micro-thoughts."""
        if not thoughts:
            return quality

        # Productivity: average relevance to task
        quality.productivity = sum(
            t.relevance_to_current_task for t in thoughts
        ) / len(thoughts)

        # Creativity: diversity of source entries
        all_sources = set()
        for t in thoughts:
            all_sources.update(t.source_entry_ids)
        quality.creativity = min(1.0, len(all_sources) / max(1, len(thoughts) * 2))

        # Circularity: detect repeated content patterns
        current_hashes = []
        for t in thoughts:
            h = hash(t.content[:50])
            current_hashes.append(h)

        # Check overlap with recent thought hashes
        recent = set(self._recent_thought_hashes)
        if current_hashes:
            overlap = sum(1 for h in current_hashes if h in recent) / len(current_hashes)
            quality.circularity = overlap

        # Update history
        for h in current_hashes:
            self._recent_thought_hashes.append(h)

        # Coherence: how well do thoughts relate to each other?
        if len(thoughts) >= 2:
            type_consistency = len(set(t.thought_type for t in thoughts)) / len(thoughts)
            quality.coherence = 1.0 - type_consistency * 0.5  # More consistent → higher coherence

        return quality

    def _evaluate_unified(self, unified_thought: Any,
                           quality: ThoughtQuality) -> ThoughtQuality:
        """Evaluate a unified thought from InternalMonologue."""
        # If unified_thought is a dict or has attributes
        if isinstance(unified_thought, dict):
            quality.productivity = unified_thought.get('confidence', 0.5)
            quality.coherence = unified_thought.get('coherence', 0.5)
        elif hasattr(unified_thought, 'confidence'):
            quality.productivity = getattr(unified_thought, 'confidence', 0.5)
            quality.coherence = getattr(unified_thought, 'coherence', 0.5)

        return quality

    def _generate_recommendation(self, quality: ThoughtQuality) -> str:
        """Generate a recommendation based on quality assessment."""
        if quality.circularity > self._circularity_threshold:
            self._redirects += 1
            return "redirect"  # Thoughts are circular, need redirection

        if quality.value_of_control < 0.3:
            return "pause"  # Not worth continuing to think

        if quality.productivity < 0.3 and quality.creativity < 0.3:
            return "redirect"  # Neither productive nor creative

        if quality.productivity > 0.7:
            return "deepen"  # Productive thoughts, go deeper

        return "continue"  # Default: keep going

    def should_redirect(self) -> bool:
        """Quick check: should the thought stream be redirected?"""
        recent = list(self._recent_thought_hashes)[-10:]
        if len(recent) < 5:
            return False
        unique = len(set(recent))
        return unique / len(recent) < 0.5  # >50% duplicates → redirect

    def get_stats(self) -> Dict[str, Any]:
        return {
            'total_evaluations': self._total_evaluations,
            'redirects': self._redirects,
            'recent_thought_hash_count': len(self._recent_thought_hashes),
        }
