# [12] ThoughtBuffer — Circular Buffer (Global Workspace)
# ═══════════════════════════════════════════════════════════════════

class ThoughtBuffer:
    """
    Circular buffer of recent micro-thoughts.

    Implements Baars' Global Workspace: thoughts compete for "conscious"
    broadcast. Only the most activated thoughts reach the workspace
    and influence response generation.

    Capacity follows Lisman-Jensen: ~7±2 simultaneously active thoughts.
    """

    def __init__(self, capacity: int = 100, workspace_size: int = 7):
        self._buffer: deque = deque(maxlen=capacity)
        self._workspace_size = workspace_size
        self._lock = threading.Lock()
        self._total_thoughts = 0
        self._total_conscious = 0
        logger.info(f"ThoughtBuffer initialized (capacity={capacity}, ws={workspace_size})")

    @property
    def size(self) -> int:
        """Number of thoughts in buffer."""
        return len(self._buffer)

    def add(self, thought: MicroThought) -> None:
        """Add a thought to the buffer."""
        with self._lock:
            self._buffer.append(thought)
            self._total_thoughts += 1

    def get_workspace(self, context: Optional[str] = None) -> List[MicroThought]:
        """
        Get the current Global Workspace — the most activated thoughts.

        If context is provided, boosts relevance of thoughts matching it.
        Returns up to workspace_size thoughts sorted by activation.
        """
        with self._lock:
            thoughts = list(self._buffer)

        if not thoughts:
            return []

        # Decay all thoughts
        for t in thoughts:
            t.decay()

        # If context provided, boost relevance of matching thoughts
        if context:
            context_words = set(context.lower().split())
            for t in thoughts:
                thought_words = set(t.content.lower().split())
                overlap = len(context_words & thought_words)
                if overlap > 0:
                    t.activation += 0.1 * overlap

        # Sort by activation * relevance
        thoughts.sort(
            key=lambda t: t.activation * (0.5 + 0.5 * t.relevance_to_current_task),
            reverse=True
        )

        # Top-K become "conscious"
        workspace = thoughts[:self._workspace_size]
        for t in workspace:
            if not t.was_conscious:
                t.was_conscious = True
                self._total_conscious += 1

        return workspace

    def get_recent(self, n: int = 10) -> List[MicroThought]:
        """Get the N most recent thoughts."""
        with self._lock:
            items = list(self._buffer)
        return items[-n:] if len(items) >= n else items

    def get_by_type(self, thought_type: str) -> List[MicroThought]:
        """Get all thoughts of a given type."""
        with self._lock:
            return [t for t in self._buffer if t.thought_type == thought_type]

    def clear(self) -> None:
        """Clear all thoughts."""
        with self._lock:
            self._buffer.clear()

    def get_stats(self) -> Dict[str, Any]:
        """Get buffer statistics."""
        return {
            'size': self.size,
            'total_thoughts': self._total_thoughts,
            'total_conscious': self._total_conscious,
            'consciousness_rate': (self._total_conscious / max(1, self._total_thoughts)),
        }


