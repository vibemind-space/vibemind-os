# [13] AssociativeThinking — Semantic Chain Hopping
# ═══════════════════════════════════════════════════════════════════

class AssociativeThinking:
    """
    Associative thinking through semantic chain hopping in the Moltbook.

    Takes current context, searches semantically, then follows
    association chains (A → B → C) with relevance decay per hop.

    Integration:
      - EntorhinalCortex.cognitive_map_distance() for conceptual distances
      - LocusCoeruleus.explore_exploit_balance() for creativity temperature
    """

    def __init__(self, moltbook=None, entorhinal=None, locus_coeruleus=None,
                 max_hops: int = 3, decay_per_hop: float = 0.5):
        self._moltbook = moltbook            # MoltbookStore
        self._entorhinal = entorhinal        # EntorhinalCortex (optional)
        self._locus_coeruleus = locus_coeruleus  # LocusCoeruleus (optional)
        self._max_hops = max_hops
        self._decay_per_hop = decay_per_hop
        self._total_chains = 0
        self._total_hops = 0
        logger.info("AssociativeThinking initialized")

    def associate(self, seed_text: str, temperature: float = 0.5,
                  max_results: int = 5) -> List[MicroThought]:
        """
        Generate associative thoughts from a seed text.

        Args:
            seed_text: Starting point for association chain
            temperature: Creativity level (0=focused, 1=wild associations)
            max_results: Maximum thoughts to generate

        Returns:
            List of MicroThought representing the association chain
        """
        if not self._moltbook:
            return []

        # Get creativity temperature from LC if available
        if self._locus_coeruleus:
            try:
                lc_state = self._locus_coeruleus.process({'task_type': 'creative'})
                if isinstance(lc_state, dict):
                    temperature = lc_state.get('explore_exploit_balance', temperature)
            except Exception:
                pass

        thoughts: List[MicroThought] = []
        visited_ids: set = set()
        current_text = seed_text
        relevance = 1.0

        for hop in range(self._max_hops):
            if relevance < 0.1:
                break

            # Search Moltbook for associations
            try:
                # Adjust top_k based on temperature (higher temp = more candidates)
                top_k = max(3, int(5 + temperature * 10))
                results = self._moltbook.query_semantic(
                    current_text, top_k=top_k,
                    threshold=max(0.1, 0.5 - temperature * 0.3)
                )
            except Exception:
                break

            if not results:
                break

            # Filter already visited
            candidates = [r for r in results if r.id not in visited_ids]
            if not candidates:
                break

            # Select next hop (temperature controls randomness)
            if temperature > 0.5 and len(candidates) > 1:
                # Higher temperature → more random selection
                idx = random.randint(0, min(len(candidates) - 1, int(temperature * len(candidates))))
                selected = candidates[idx]
            else:
                selected = candidates[0]

            visited_ids.add(selected.id)

            # Create thought from this hop
            thought = MicroThought(
                content=f"[hop_{hop}] {selected.content[:200]}",
                relevance_to_current_task=relevance,
                emotional_charge=selected.emotional_valence,
                arousal=selected.emotional_arousal,
                source_entry_ids=[selected.id],
                thought_type="association",
                activation=relevance,
            )
            thoughts.append(thought)

            # Prepare next hop
            current_text = selected.content
            relevance *= self._decay_per_hop
            self._total_hops += 1

        self._total_chains += 1
        return thoughts[:max_results]

    def find_creative_bridge(self, concept_a: str, concept_b: str,
                              max_bridge_length: int = 3) -> List[MicroThought]:
        """
        Find a creative bridge between two concepts via association chain.

        Useful for analogy generation: "A is to B as C is to D".
        """
        if not self._moltbook:
            return []

        # Get associations from both endpoints
        thoughts_a = self.associate(concept_a, temperature=0.7, max_results=max_bridge_length)
        thoughts_b = self.associate(concept_b, temperature=0.7, max_results=max_bridge_length)

        # Find overlap (concepts reachable from both sides)
        ids_a = set()
        for t in thoughts_a:
            ids_a.update(t.source_entry_ids)

        bridge = []
        for t in thoughts_b:
            for eid in t.source_entry_ids:
                if eid in ids_a:
                    bridge_thought = MicroThought(
                        content=f"[bridge] {t.content}",
                        relevance_to_current_task=0.8,
                        thought_type="association",
                        source_entry_ids=t.source_entry_ids,
                    )
                    bridge.append(bridge_thought)

        return bridge

    def get_stats(self) -> Dict[str, Any]:
        return {
            'total_chains': self._total_chains,
            'total_hops': self._total_hops,
            'avg_hops_per_chain': self._total_hops / max(1, self._total_chains),
        }


