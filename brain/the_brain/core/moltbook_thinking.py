# [14] EmotionalThinking — Affect-Modulated Thought Generation
# ═══════════════════════════════════════════════════════════════════

class EmotionalThinking:
    """
    Emotion-modulated thought generation.

    Based on Fredrickson's Broaden-and-Build theory:
      - Positive affect → broader associations (exploration)
      - Negative affect → narrower, focused thinking (threat focus)

    Integration:
      - CoreAffectSpace for valence × arousal
      - AmygdalaComplex for threat-relevant thinking
    """

    def __init__(self, core_affect=None, amygdala=None):
        self._core_affect = core_affect    # CoreAffectSpace (optional)
        self._amygdala = amygdala          # AmygdalaComplex (optional)
        self._current_valence = 0.0
        self._current_arousal = 0.5
        logger.info("EmotionalThinking initialized")

    def update_affect(self, valence: float = 0.0, arousal: float = 0.5) -> None:
        """Update current emotional state."""
        self._current_valence = max(-1.0, min(1.0, valence))
        self._current_arousal = max(0.0, min(1.0, arousal))

    def get_search_breadth(self) -> float:
        """
        Compute search breadth based on current affect.

        Positive valence → broader search (Broaden-and-Build)
        Negative valence → narrower search (threat focus)

        Returns: breadth factor (0.3 = very narrow, 1.0 = very broad)
        """
        # Map valence from [-1,1] to breadth [0.3, 1.0]
        breadth = 0.65 + 0.35 * self._current_valence
        return max(0.3, min(1.0, breadth))

    def get_similarity_threshold(self) -> float:
        """
        Compute similarity threshold based on affect.

        Positive → lower threshold (accept more distant associations)
        Negative → higher threshold (only close matches)
        """
        base = 0.5
        adjustment = -0.2 * self._current_valence  # positive valence lowers threshold
        return max(0.2, min(0.9, base + adjustment))

    def modulate_thought(self, thought: MicroThought) -> MicroThought:
        """
        Apply emotional modulation to a thought.

        Adjusts the thought's emotional charge and activation based
        on current affect state.
        """
        # Emotional coloring
        thought.emotional_charge = (
            0.7 * thought.emotional_charge + 0.3 * self._current_valence
        )
        thought.arousal = (
            0.7 * thought.arousal + 0.3 * self._current_arousal
        )

        # High arousal → higher activation (more salient)
        thought.activation *= (0.8 + 0.4 * self._current_arousal)

        # Threat-relevant boost via amygdala
        if self._amygdala and self._current_valence < -0.3:
            try:
                threat = self._amygdala.process({
                    'stimulus': thought.content,
                    'stimulus_type': 'thought'
                })
                if isinstance(threat, dict):
                    threat_level = threat.get('threat_level', 0)
                    if threat_level > 0.5:
                        thought.activation *= 1.5  # Threat-relevant thoughts get boosted
                        thought.thought_type = "threat_assessment"
            except Exception:
                pass

        return thought

    def get_state(self) -> Dict[str, Any]:
        return {
            'valence': self._current_valence,
            'arousal': self._current_arousal,
            'search_breadth': self.get_search_breadth(),
            'similarity_threshold': self.get_similarity_threshold(),
        }


